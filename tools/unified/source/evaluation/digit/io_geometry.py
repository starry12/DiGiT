"""Versioned mixed-I/O geometry and a deterministic CPU reference model.

This module is the Phase 9B contract shared by artifact generation, receipt
validation and the native GIDS/BaM path.  All addresses are byte based;
``storage_row`` remains the public feature index used by the artifact and
sampler.
"""

